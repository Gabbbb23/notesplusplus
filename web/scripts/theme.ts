import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  argbFromHex,
  customColor,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeTonalSpot,
  type DynamicColor,
  type DynamicScheme,
} from "@material/material-color-utilities";

/*
 * The Material 3 colour roles for src/theme.css, light and dark, from one source colour.
 * `npm run theme` rewrites the file; test/theme.test.ts fails while the file and this script disagree.
 */

export const SOURCE = "#1a73e8";

/** Colours M3 has no role for, harmonized toward the source the way Material Theme Builder does it. */
export const EXTENDED = [
  { name: "success", value: "#188038" },
  { name: "warning", value: "#f9ab00" },
] as const;

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "inversePrimary",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "surface",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "onSurface",
  "surfaceVariant",
  "onSurfaceVariant",
  "inverseSurface",
  "inverseOnSurface",
  "outline",
  "outlineVariant",
  "shadow",
  "scrim",
  "surfaceTint",
] as const satisfies readonly (keyof typeof MaterialDynamicColors)[];

const kebab = (name: string) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function schemeTokens(scheme: DynamicScheme, dark: boolean): string[] {
  const lines = ROLES.map((role) => {
    const color = MaterialDynamicColors[role] as DynamicColor;
    return `--md-sys-color-${kebab(role)}: ${hexFromArgb(color.getArgb(scheme))};`;
  });
  for (const { name, value } of EXTENDED) {
    const group = customColor(argbFromHex(SOURCE), { name, value: argbFromHex(value), blend: true });
    const tones = dark ? group.dark : group.light;
    lines.push(
      `--md-sys-color-${name}: ${hexFromArgb(tones.color)};`,
      `--md-sys-color-on-${name}: ${hexFromArgb(tones.onColor)};`,
      `--md-sys-color-${name}-container: ${hexFromArgb(tones.colorContainer)};`,
      `--md-sys-color-on-${name}-container: ${hexFromArgb(tones.onColorContainer)};`,
    );
  }
  return lines;
}

export function buildThemeCss(): string {
  const source = Hct.fromInt(argbFromHex(SOURCE));
  const light = schemeTokens(new SchemeTonalSpot(source, false, 0), false);
  const dark = schemeTokens(new SchemeTonalSpot(source, true, 0), true);
  const indent = (lines: string[], pad: string) => lines.map((l) => `${pad}${l}`).join("\n");
  return `/*
 * Material 3 colour roles, generated by scripts/theme.ts from the source colour ${SOURCE}
 * (tonal spot scheme, standard contrast). Do not edit by hand: change the script and run npm run theme.
 *
 * The dark scheme follows the system setting. The print page (.print-page) always stays light,
 * because a PDF is read on paper.
 */
:root {
  color-scheme: light dark;
${indent(light, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not(:has(.print-page)) {
${indent(dark, "    ")}
  }
}

:root:has(.print-page) {
  color-scheme: light;
}
`;
}

export const THEME_CSS_PATH = fileURLToPath(new URL("../src/theme.css", import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(THEME_CSS_PATH, buildThemeCss());
  console.log(`Wrote ${THEME_CSS_PATH}`);
}
